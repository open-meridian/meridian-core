//! Write the broker's configuration from the grant table and the registry.
//!
//! One implementation of the policy, in the image every deployment runs, so a
//! bundled broker generates its own configuration at start from the grants it
//! was given and the instances it was configured with. Compose runs the same
//! binary to write the file it mounts, which is what keeps the two honest.
//!
//! Passwords are never read here. Each user names the environment variable the
//! broker reads its own password from, so this writes a file nobody has to
//! protect.

use meridian_runtime::broker::{rendered, users, Instance};

const HEADER: &str = "\
# Generated by `meridian-broker-config` from the grant table. Do not edit.
#
# The grant table is the policy; this is the broker saying the same thing in
# its own language. Run `make nats-permissions` after changing grants.

";

fn main() {
    if let Err(failed) = run() {
        eprintln!("broker-config: {failed}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let mut grants = "deploy/grants.example.json".to_string();
    let mut instances = "deploy/instances.example.json".to_string();
    let mut topics = "deploy/topics.tsv".to_string();
    let mut out = String::new();
    let mut dev_users = String::new();

    let mut args = std::env::args().skip(1);
    while let Some(argument) = args.next() {
        let mut value = || {
            args.next()
                .ok_or_else(|| format!("{argument} needs a path"))
        };
        match argument.as_str() {
            "--grants" => grants = value()?,
            "--instances" => instances = value()?,
            "--topics" => topics = value()?,
            "--out" => out = value()?,
            // Development identities, merged only when asked for. What they
            // produce is not what a chart ships.
            "--dev-users" => dev_users = value()?,
            other => return Err(format!("{other} is not an argument this takes")),
        }
    }

    let read = |path: &str| {
        std::fs::read_to_string(path)
            .map_err(|failed| format!("{path} could not be read: {failed}"))
    };

    let manifest = read(&topics)?;
    // A deployment with no grant table admits no plugin, which is the right
    // default for a file that decides access: the broker still serves the
    // components, and a plugin that connects is refused every topic.
    let grants: serde_json::Value = match std::fs::read_to_string(&grants) {
        Ok(text) => serde_json::from_str(&text)
            .map_err(|failed| format!("the grant table is not JSON: {failed}"))?,
        Err(_) => serde_json::json!({"roles": {}}),
    };
    let instances: serde_json::Value = match std::fs::read_to_string(&instances) {
        Ok(text) => serde_json::from_str(&text)
            .map_err(|failed| format!("the instance list is not JSON: {failed}"))?,
        Err(_) => serde_json::json!({"instances": []}),
    };

    let launched: Vec<Instance> = instances["instances"]
        .as_array()
        .map(|items| {
            items
                .iter()
                .map(|item| Instance {
                    instance_id: item["instance_id"].as_str().unwrap_or_default().to_string(),
                    role: item["role"].as_str().unwrap_or_default().to_string(),
                    tags: item["tags"]
                        .as_array()
                        .map(|tags| {
                            tags.iter()
                                .filter_map(|tag| tag.as_str())
                                .map(String::from)
                                .collect()
                        })
                        .unwrap_or_default(),
                })
                .collect()
        })
        .unwrap_or_default();

    let mut admitted = users(&manifest, &grants, &launched)?;
    if !dev_users.is_empty() {
        let extra: serde_json::Value = serde_json::from_str(&read(&dev_users)?)
            .map_err(|failed| format!("the development identities are not JSON: {failed}"))?;
        for user in extra["users"].as_array().into_iter().flatten() {
            let listed = |key: &str| {
                user[key]
                    .as_array()
                    .map(|items| {
                        items
                            .iter()
                            .filter_map(|item| item.as_str())
                            .map(String::from)
                            .collect()
                    })
                    .unwrap_or_default()
            };
            let name = user["user"].as_str().unwrap_or_default().to_string();
            admitted.push(meridian_runtime::broker::User {
                note: format!("{name}: a development identity, from {dev_users}"),
                password_env: user["password_env"]
                    .as_str()
                    .unwrap_or_default()
                    .to_string(),
                user: name,
                publish: listed("publish"),
                subscribe: listed("subscribe"),
            });
        }
    }

    let configuration = rendered(HEADER, &admitted);
    match out.as_str() {
        "" => print!("{configuration}"),
        path => std::fs::write(path, configuration)
            .map_err(|failed| format!("{path} could not be written: {failed}"))?,
    }
    Ok(())
}
