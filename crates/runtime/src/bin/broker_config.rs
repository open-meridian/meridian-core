//! Write the broker's configuration from the contract and the instances.
//!
//! One implementation of the policy, in the image every deployment runs, so a
//! bundled broker generates its own configuration at start from the instances
//! it was configured with. What each may do is the contract's, compiled in
//! (decisions/020), so there is no grant table to pass. Compose runs the same
//! binary to write the file it mounts, which is what keeps the two honest.
//!
//! Passwords are never read here. Each user names the environment variable the
//! broker reads its own password from, so this writes a file nobody has to
//! protect.
//!
//! `meridian-broker-config serve` is the bundled broker's own process: it
//! runs `nats-server` as its child, and watches for plugins launched after
//! install, giving each a credential and the broker a configuration that
//! admits it -- by a bcrypt hash, so the file still holds no password -- and
//! having its child reload (spec/the-local-plugin-registry, decision 3). The
//! broker is its child so that the reload is a signal to its own process:
//! signalling across containers would take a shared process namespace, in
//! which the watcher could read the broker's environment, and with it every
//! component's password.

use meridian_runtime::broker::{rendered, users, Instance};
use meridian_sidecar::Contract;

const HEADER: &str = "\
# Generated by `meridian-broker-config` from the contract. Do not edit.
#
# The contract is the policy; this is the broker saying the same thing in its
# own language. Run `make nats-permissions` after the contract moves.

# The largest message the broker carries, stated rather than left to the
# broker's default. The bus reads it from the broker and refuses a question
# or an answer past it, and a paged answer is budgeted under it (the plugin
# catalogue's page ends at 512 KiB). Never raised to fit an answer: page it.
max_payload: 1MB

# A client that stops answering -- a frozen machine, a paused process -- is
# dropped within about 6 s: pinged every 2 s, and let go after two pings
# unanswered (step 3b). Until then the broker still hands it its share of a
# queue group's requests, which a frozen writer never answers, while the
# standby that took its lease serves the rest. The broker's own default
# (two minutes, two pings) held them for four.
ping_interval: \"2s\"
ping_max: 2

";

fn main() {
    meridian_runtime::answer_version();
    let failed = if std::env::args().nth(1).as_deref() == Some("serve") {
        tracing_subscriber::fmt()
            .with_env_filter(
                tracing_subscriber::EnvFilter::try_from_default_env()
                    .unwrap_or_else(|_| "info".into()),
            )
            .init();
        serve::run().err()
    } else {
        run().err()
    };
    if let Some(failed) = failed {
        eprintln!("broker-config: {failed}");
        std::process::exit(1);
    }
}

/// The instance list the chart renders.
fn chart_instances(path: &str) -> Result<Vec<Instance>, String> {
    let instances: serde_json::Value = match std::fs::read_to_string(path) {
        Ok(text) => serde_json::from_str(&text)
            .map_err(|failed| format!("the instance list is not JSON: {failed}"))?,
        Err(_) => serde_json::json!({"instances": []}),
    };
    instances["instances"]
        .as_array()
        .into_iter()
        .flatten()
        .map(instance)
        .collect()
}

mod serve {
    use std::collections::BTreeMap;
    use std::time::Duration;

    use meridian_first_run::cluster::ApiServer;
    use meridian_runtime::broker::Instance;
    use meridian_runtime::launched::{self, LAUNCHED_SELECTOR};
    use meridian_sidecar::Contract;
    use tokio::signal::unix::{signal, SignalKind};

    use super::chart_instances;

    struct Args {
        nats: String,
        instances: String,
        out: String,
        secret: String,
        broker: String,
        every: Duration,
        /// The cluster this server is one of, with three (step 3b): its
        /// name, and every server's route by name, its own included.
        cluster: String,
        routes: Vec<String>,
        /// JetStream's file store for the analytics units' work queue, with
        /// three servers, as the most it may hold; empty for none.
        jetstream: String,
        /// Where JetStream keeps it: the server's own volume.
        jetstream_store: String,
        /// The broker's bounds (stage M; the resilience spec's section
        /// 10a): each client's pending bytes before it is cut off as a slow
        /// consumer (`broker.limits.maxPending`), the largest message
        /// (`broker.limits.maxPayload`), and JetStream's memory
        /// (`broker.jetstream.maxMemory`).
        max_pending: String,
        max_payload: String,
        jetstream_memory: String,
        /// The directory of this server's certificate, key and the
        /// internal CA, where the deployment's internal TLS is on; empty
        /// for none (ruling 1084).
        tls: String,
    }

    fn args() -> Result<Args, String> {
        let mut parsed = Args {
            nats: "nats-server".into(),
            instances: String::new(),
            out: String::new(),
            secret: String::new(),
            broker: String::new(),
            every: Duration::from_secs(5),
            cluster: String::new(),
            routes: Vec::new(),
            jetstream: String::new(),
            jetstream_store: "/data/jetstream".into(),
            max_pending: super::MAX_PENDING.into(),
            max_payload: super::MAX_PAYLOAD.into(),
            jetstream_memory: super::JETSTREAM_MEMORY.into(),
            tls: String::new(),
        };
        let mut args = std::env::args().skip(2);
        while let Some(argument) = args.next() {
            let value = args
                .next()
                .ok_or_else(|| format!("{argument} needs a value"))?;
            match argument.as_str() {
                "--nats" => parsed.nats = value,
                "--instances" => parsed.instances = value,
                "--out" => parsed.out = value,
                // The Secret the chart made for launched plugins' credentials,
                // the one thing this may write.
                "--secret" => parsed.secret = value,
                // Where a sidecar reaches the broker, for its connection string.
                "--broker" => parsed.broker = value,
                "--cluster" => parsed.cluster = value,
                "--route" => parsed.routes.push(value),
                "--jetstream" => parsed.jetstream = value,
                "--jetstream-store" => parsed.jetstream_store = value,
                "--max-pending" => {
                    parsed.max_pending = super::size(&value, "broker.limits.maxPending")?
                }
                "--max-payload" => {
                    parsed.max_payload = super::size(&value, "broker.limits.maxPayload")?
                }
                "--jetstream-memory" => {
                    parsed.jetstream_memory = super::size(&value, "broker.jetstream.maxMemory")?
                }
                "--tls" => parsed.tls = value,
                "--every" => {
                    parsed.every = Duration::from_secs(
                        value
                            .parse()
                            .map_err(|_| format!("--every {value} is not seconds"))?,
                    )
                }
                other => return Err(format!("{other} is not an argument serve takes")),
            }
        }
        for (name, value) in [
            ("--out", &parsed.out),
            ("--secret", &parsed.secret),
            ("--broker", &parsed.broker),
        ] {
            if value.is_empty() {
                return Err(format!("serve needs {name}"));
            }
        }
        if !parsed.routes.is_empty() && parsed.cluster.is_empty() {
            return Err("--route needs --cluster".into());
        }
        Ok(parsed)
    }

    /// The header, with this server's cluster and JetStream where it has them.
    fn header(args: &Args) -> String {
        format!(
            "{}{}{}",
            super::bounded(&args.max_pending, &args.max_payload),
            super::secured(&args.tls),
            super::clustered(
                &args.cluster,
                &args.routes,
                &args.jetstream,
                &args.jetstream_store,
                &args.jetstream_memory,
                &args.tls,
            )
        )
    }

    /// Hashes made once per password: bcrypt is slow on purpose.
    type Hashes = BTreeMap<(String, String), String>;

    /// The launched plugins' credentials put right, and the configuration
    /// admitting them.
    async fn reconciled(
        api: &ApiServer,
        args: &Args,
        chart: &[Instance],
        hashes: &mut Hashes,
    ) -> Result<String, String> {
        let list = api
            .deployments(LAUNCHED_SELECTOR)
            .await
            .map_err(|failed| failed.0)?;
        let launched = launched::from_deployments(&list);
        let held = api
            .secret_text(&args.secret)
            .await
            .map_err(|failed| failed.0)?;
        let reconciled = launched::reconcile(&launched, &held, &args.broker, launched::mint);
        if !reconciled.changes.is_empty() {
            api.patch_secret_text(&args.secret, &reconciled.changes)
                .await
                .map_err(|failed| failed.0)?;
            for (key, change) in &reconciled.changes {
                if key.ends_with(".password") {
                    let instance = key.trim_end_matches(".password");
                    match change {
                        Some(_) => tracing::info!(instance, "a credential for a launched plugin"),
                        None => tracing::info!(instance, "a stopped plugin's credential removed"),
                    }
                }
            }
        }
        let mut by_instance = BTreeMap::new();
        for (instance, password) in &reconciled.passwords {
            let key = (instance.clone(), password.clone());
            if !hashes.contains_key(&key) {
                let hashing = password.clone();
                let hash = tokio::task::spawn_blocking(move || {
                    bcrypt::hash(hashing, bcrypt::DEFAULT_COST)
                })
                .await
                .map_err(|failed| failed.to_string())?
                .map_err(|failed| failed.to_string())?;
                hashes.insert(key.clone(), hash);
            }
            by_instance.insert(instance.clone(), hashes[&key].clone());
        }
        hashes.retain(|(instance, _), _| reconciled.passwords.contains_key(instance));
        let (configuration, left_out) = launched::configuration(
            &header(args),
            Contract::embedded(),
            chart,
            &launched,
            &by_instance,
        )?;
        for why in left_out {
            tracing::warn!("a launched plugin is not admitted: {why}");
        }
        Ok(configuration)
    }

    fn signal_child(pid: Option<u32>, signal: libc::c_int) {
        if let Some(pid) = pid {
            // Its own child, so no right beyond this process's is needed.
            unsafe {
                libc::kill(pid as libc::pid_t, signal);
            }
        }
    }

    pub fn run() -> Result<(), String> {
        let args = args()?;
        tokio::runtime::Builder::new_multi_thread()
            .enable_all()
            .build()
            .map_err(|failed| failed.to_string())?
            .block_on(serve(args))
    }

    async fn serve(args: Args) -> Result<(), String> {
        let chart = chart_instances(&args.instances)?;
        let api = ApiServer::in_cluster(meridian_runtime::clock()).map_err(|failed| failed.0)?;
        let mut hashes = Hashes::new();

        // The broker starts whatever the cluster's API says, with the chart's
        // instances at least: the components are not held up by a plugin.
        let mut current = match reconciled(&api, &args, &chart, &mut hashes).await {
            Ok(configuration) => configuration,
            Err(failed) => {
                tracing::warn!("launched plugins could not be read yet: {failed}");
                launched::configuration(
                    &header(&args),
                    Contract::embedded(),
                    &chart,
                    &[],
                    &BTreeMap::new(),
                )?
                .0
            }
        };
        // DIAGNOSTIC (c30-d2, never landed): JetStream's own view on
        // 127.0.0.1:8222 where MERIDIAN_BROKER_MONITOR is set.
        let monitored = |said: String| {
            if std::env::var_os("MERIDIAN_BROKER_MONITOR").is_some() {
                format!("{said}http: \"127.0.0.1:8222\"\n")
            } else {
                said
            }
        };
        current = monitored(current);
        std::fs::write(&args.out, &current)
            .map_err(|failed| format!("{} could not be written: {failed}", args.out))?;

        let mut broker = tokio::process::Command::new(&args.nats)
            .args(["-c", &args.out])
            .kill_on_drop(true)
            .spawn()
            .map_err(|failed| format!("{} did not start: {failed}", args.nats))?;
        let pid = broker.id();
        tracing::info!(pid, "the broker is running");

        let mut terminate = signal(SignalKind::terminate()).map_err(|failed| failed.to_string())?;
        let mut every = tokio::time::interval(args.every);
        every.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
        loop {
            tokio::select! {
                ended = broker.wait() => {
                    // The broker is this container: it stopping is this
                    // stopping, and the orchestrator restarts both.
                    let status = ended.map_err(|failed| failed.to_string())?;
                    return Err(format!("the broker stopped: {status}"));
                }
                _ = terminate.recv() => {
                    signal_child(pid, libc::SIGTERM);
                    let _ = broker.wait().await;
                    return Ok(());
                }
                _ = every.tick() => {
                    match reconciled(&api, &args, &chart, &mut hashes).await {
                        Ok(configuration) if monitored(configuration.clone()) != current => {
                            let configuration = monitored(configuration);
                            std::fs::write(&args.out, &configuration)
                                .map_err(|failed| format!("{} could not be written: {failed}", args.out))?;
                            signal_child(pid, libc::SIGHUP);
                            current = configuration;
                            tracing::info!("the broker reloaded its configuration");
                        }
                        Ok(_) => {}
                        Err(failed) => tracing::warn!("launched plugins could not be read: {failed}"),
                    }
                }
            }
        }
    }
}

/// A server's cluster and JetStream (step 3b; spec/a-deployment-scales-out-
/// and-fails-over-by-configuration section 4, question 6), as the broker's
/// configuration says them; nothing for a server alone.
///
/// Its name from `MERIDIAN_BROKER_SERVER_NAME`, its pod's. Its routes, one
/// per server, each by the variable holding its URL with the cluster's own
/// credential, which `cluster.authorization` checks (read from
/// `MERIDIAN_NATS__ROUTES`, like every other password here): no client
/// credential can join the cluster, and nothing in this file is a password.
/// JetStream only for the analytics units' work queue, never a record
/// (decisions/024): on file in `store`, the server's own volume, with its
/// Raft state, so a server restarted -- one at a time, as an upgrade rolls
/// them -- rejoins with what it held. Held in memory, a rolling restart left
/// the three answering "no suitable peers for placement" for twelve minutes
/// (CI 42294258528).
/// TLS on every connection to this server, where the deployment's internal
/// TLS is on (the chart's `tls.internal.enabled`; ruling 1084): its
/// certificate and key from `dir`, made by the chart from the internal CA.
/// A server with `tls` refuses a client that does not speak it, so a
/// plaintext connection is refused, not merely discouraged. Nothing for
/// none.
fn secured(dir: &str) -> String {
    if dir.is_empty() {
        return String::new();
    }
    format!(
        "# Internal TLS (ruling 1084): every client over TLS, or not at all.\n\
         tls {{\n{}}}\n\n",
        tls_block(dir)
    )
}

/// The certificate, key and CA of a `tls` block, under `dir`.
fn tls_block(dir: &str) -> String {
    format!(
        "  cert_file: {:?}\n  key_file: {:?}\n  ca_file: {:?}\n  timeout: 2\n",
        format!("{dir}/tls.crt"),
        format!("{dir}/tls.key"),
        format!("{dir}/ca.crt"),
    )
}

/// `broker.limits.maxPending`, `broker.limits.maxPayload` and
/// `broker.jetstream.maxMemory` where the chart says nothing (stage M): the
/// broker's own pending default, the 1 MiB every paged answer is budgeted
/// under, and what JetStream held in memory before.
const MAX_PENDING: &str = "64MB";
const MAX_PAYLOAD: &str = "1MB";
const JETSTREAM_MEMORY: &str = "16MB";

/// A size as the broker reads one -- a whole number of bytes, or of KB, MB or
/// GB -- or refused, naming the chart value it came from.
fn size(value: &str, name: &str) -> Result<String, String> {
    let value = value.trim();
    let digits = value.trim_end_matches(|c: char| c.is_ascii_alphabetic());
    let unit = &value[digits.len()..];
    if digits.is_empty()
        || !digits.bytes().all(|b| b.is_ascii_digit())
        || digits.parse::<u64>().map_or(true, |n| n == 0)
        || !["", "KB", "MB", "GB"].contains(&unit)
    {
        return Err(format!(
            "{name} is {value:?}; a whole number above 0 of bytes, KB, MB or GB"
        ));
    }
    Ok(value.to_string())
}

/// The header with the broker's bounds (stage M; the resilience spec's
/// section 10a): the largest message as the chart says, and each client's
/// pending bytes, past which the broker cuts that client off alone as a
/// slow consumer and every other keeps its deliveries.
fn bounded(max_pending: &str, max_payload: &str) -> String {
    let header = HEADER.replace(
        &format!("\nmax_payload: {MAX_PAYLOAD}\n"),
        &format!("\nmax_payload: {max_payload}\n"),
    );
    format!(
        "{header}# A client that stops reading is cut off alone, as a slow consumer, once\n\
         # this much is pending for it (broker.limits.maxPending; stage M).\n\
         max_pending: {max_pending}\n\n"
    )
}

fn clustered(
    cluster: &str,
    routes: &[String],
    jetstream: &str,
    store: &str,
    memory: &str,
    tls: &str,
) -> String {
    let mut said = String::new();
    if !cluster.is_empty() {
        said.push_str(
            "# One of a cluster (step 3b): this server by its pod's name, its routes to\n\
             # every server by theirs, joined with the cluster's own credential.\n\
             server_name: $MERIDIAN_BROKER_SERVER_NAME\n",
        );
        said.push_str(&format!(
            "cluster {{\n  name: {cluster:?}\n  listen: \"0.0.0.0:6222\"\n  \
             authorization {{\n    user: \"routes\"\n    password: $MERIDIAN_NATS__ROUTES\n  }}\n  \
             routes: [\n"
        ));
        for route in routes {
            said.push_str(&format!("    ${route}\n"));
        }
        said.push_str("  ]\n");
        if !tls.is_empty() {
            // The routes between servers too, each verified by the name
            // its route gives it.
            said.push_str("  tls {\n");
            for line in tls_block(tls).lines() {
                said.push_str(&format!("  {line}\n"));
            }
            said.push_str("  }\n");
        }
        said.push_str("}\n\n");
    }
    if !jetstream.is_empty() {
        said.push_str(&format!(
            "# The analytics units' work queue, kept on three servers, each on its own volume.\n\
             jetstream {{\n  store_dir: {store:?}\n  \
             max_memory_store: {memory}\n  max_file_store: {jetstream}\n}}\n\n"
        ));
    }
    said
}

/// An instance entry: `{"instance_id", "roles": [...]}` for a plugin's
/// sidecar, or `{"instance_id", "component"}` for a component holding its own
/// credential under an instance name, as the dashboard does.
fn instance(item: &serde_json::Value) -> Result<Instance, String> {
    let instance_id = item["instance_id"]
        .as_str()
        .filter(|id| !id.is_empty())
        .ok_or_else(|| format!("an instance has no instance_id: {item}"))?
        .to_string();
    if let Some(component) = item["component"].as_str() {
        return Ok(Instance::component(instance_id, component));
    }
    if item.get("role").is_some() {
        return Err(format!(
            "{instance_id} names a single `role`; a plugin holds `roles`, a list (decisions/020)"
        ));
    }
    let roles: Vec<&str> = item["roles"]
        .as_array()
        .map(|items| items.iter().filter_map(|role| role.as_str()).collect())
        .unwrap_or_default();
    // The datasets it is entitled to (contract v18), where the list names
    // them: compose and the harness write them at start and on `entitle`.
    let datasets: Vec<String> = item["datasets"]
        .as_array()
        .map(|items| {
            items
                .iter()
                .filter_map(|dataset| dataset.as_str().map(String::from))
                .collect()
        })
        .unwrap_or_default();
    Ok(Instance::plugin(instance_id, &roles).with_datasets(datasets))
}

/// Each plugin instance's datasets as `path` names them, written into the
/// instance list in place of its own; a file not there names none.
fn entitled(instances: &mut serde_json::Value, path: &str) -> Result<(), String> {
    let Ok(text) = std::fs::read_to_string(path) else {
        return Ok(());
    };
    let named: std::collections::BTreeMap<String, Vec<String>> = serde_json::from_str(&text)
        .map_err(|failed| {
            format!("{path} is not a JSON object of instances and their datasets: {failed}")
        })?;
    for item in instances["instances"].as_array_mut().into_iter().flatten() {
        if item.get("component").is_some() {
            continue;
        }
        let id = item["instance_id"].as_str().unwrap_or_default().to_string();
        item["datasets"] = serde_json::json!(named.get(&id).cloned().unwrap_or_default());
    }
    Ok(())
}

fn run() -> Result<(), String> {
    let mut instances = "deploy/instances.example.json".to_string();
    let mut out = String::new();
    let mut dev_users = String::new();
    let mut datasets = String::new();

    let mut args = std::env::args().skip(1);
    while let Some(argument) = args.next() {
        let mut value = || {
            args.next()
                .ok_or_else(|| format!("{argument} needs a path"))
        };
        match argument.as_str() {
            "--instances" => instances = value()?,
            "--out" => out = value()?,
            // Development identities, merged only when asked for. What they
            // produce is not what a chart ships.
            "--dev-users" => dev_users = value()?,
            // The datasets each plugin instance is entitled to (contract
            // v18), `{"<instance>": ["<dataset>", ...]}`, in place of what the
            // instance list says: what the harness's runner writes on
            // `entitle`. A file not there yet names none.
            "--datasets" => datasets = value()?,
            other => return Err(format!("{other} is not an argument this takes")),
        }
    }

    let read = |path: &str| {
        std::fs::read_to_string(path)
            .map_err(|failed| format!("{path} could not be read: {failed}"))
    };

    let mut instances: serde_json::Value = match std::fs::read_to_string(&instances) {
        Ok(text) => serde_json::from_str(&text)
            .map_err(|failed| format!("the instance list is not JSON: {failed}"))?,
        Err(_) => serde_json::json!({"instances": []}),
    };
    if !datasets.is_empty() {
        entitled(&mut instances, &datasets)?;
    }
    let launched = instances["instances"]
        .as_array()
        .into_iter()
        .flatten()
        .map(instance)
        .collect::<Result<Vec<_>, _>>()?;

    let mut admitted = users(Contract::embedded(), &launched)?;
    if !dev_users.is_empty() {
        let extra: serde_json::Value = serde_json::from_str(&read(&dev_users)?)
            .map_err(|failed| format!("the development identities are not JSON: {failed}"))?;
        for user in extra["users"].as_array().into_iter().flatten() {
            let listed = |key: &str| {
                user[key]
                    .as_array()
                    .map(|items| {
                        items
                            .iter()
                            .filter_map(|item| item.as_str())
                            .map(String::from)
                            .collect()
                    })
                    .unwrap_or_default()
            };
            let name = user["user"].as_str().unwrap_or_default().to_string();
            admitted.push(meridian_runtime::broker::User {
                note: format!("{name}: a development identity, from {dev_users}"),
                password: meridian_runtime::broker::Password::Env(
                    user["password_env"]
                        .as_str()
                        .unwrap_or_default()
                        .to_string(),
                ),
                user: name,
                publish: listed("publish"),
                subscribe: listed("subscribe"),
            });
        }
    }

    let configuration = rendered(HEADER, &admitted);
    match out.as_str() {
        "" => print!("{configuration}"),
        path => std::fs::write(path, configuration)
            .map_err(|failed| format!("{path} could not be written: {failed}"))?,
    }
    Ok(())
}

